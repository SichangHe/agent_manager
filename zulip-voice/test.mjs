import assert from 'node:assert/strict';
import http from 'node:http';
import {readFile} from 'node:fs/promises';
import {createServer} from './server.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const origin='http://127.0.0.1:18767';
const server=createServer(await readFile(new URL('./index.html',import.meta.url)),origin);
await new Promise(resolve=>server.listen(18767,'127.0.0.1',resolve));
const browser=await chromium.launch({headless:true});
try{
  const page=await browser.newPage();
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin);
  await page.locator('#draft').fill('A draft for the manager');
  await page.locator('#agent').selectOption('quals');
  assert.equal(await page.locator('#draft').inputValue(),'');
  await page.locator('#draft').fill('A different draft for Quals');
  await page.locator('#agent').selectOption('manager');
  assert.equal(await page.locator('#draft').inputValue(),'A draft for the manager');
  let submission;
  await page.route('**/api/send',async route=>{submission=route.request().postDataJSON();await route.fetch();await route.abort();});
  await page.locator('#send').click();
  await page.getByText('Connection lost.',{exact:false}).waitFor();
  await page.unroute('**/api/send');
  await page.reload();
  assert.equal(await page.locator('#draft').inputValue(),'A draft for the manager');
  await page.locator('#send').click();
  await page.getByText('Mock message delivered to Main manager (mock).',{exact:true}).waitFor();
  const messages=await (await fetch(origin+'/api/messages?agent=manager')).json();
  assert.equal(messages.filter(m=>m.sender==='human').length,1);
  const post=body=>fetch(origin+'/api/send',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json'},body:JSON.stringify(body)});
  assert.equal((await post({...submission,agent:'quals'})).status,409);
  assert.equal((await post({...submission,id:crypto.randomUUID(),agent:'nonexistent'})).status,400);
  assert.equal((await fetch(origin+'/api/send',{method:'POST',headers:{Origin:'https://evil.invalid','Content-Type':'application/json'},body:JSON.stringify(submission)})).status,403);
  const wrongHost=await new Promise((resolve,reject)=>{http.get(origin+'/api/conversations',{headers:{Host:'evil.invalid'}},response=>{response.resume();resolve(response.statusCode);}).on('error',reject);});
  assert.equal(wrongHost,403);
  await page.locator('#agent').selectOption('quals');
  assert.equal(await page.locator('#draft').inputValue(),'A different draft for Quals');
  await page.route('**/api/messages?*',route=>route.abort());
  await page.locator('#listen').click();
  await page.getByText('Connection lost.',{exact:false}).waitFor();
  assert.equal(await page.locator('#listen').isEnabled(),true);
  await page.unroute('**/api/messages?*');
  await page.locator('#listen').click();
  await page.getByText('Quals assistant (mock): This is a mock conversation.',{exact:false}).waitFor();
  assert.deepEqual(errors,[]);
}finally{await browser.close();await new Promise(resolve=>server.close(resolve));}
